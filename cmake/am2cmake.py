#!/usr/bin/env python3
"""
am2cmake.py -- write the CMakeLists.txt of every source directory below src/
from its Makefile.am.

Transitional.  While the autotools build exists, the Makefile.am files are
the master: change them as usual, run

    python3 cmake/am2cmake.py

and commit the changed CMakeLists.txt files together with the Makefile.am.
CMake runs it with --check while configuring and stops if a CMakeLists.txt
is out of date.

When autotools is dropped, delete this script and the Makefile.am files.
The generated CMakeLists.txt files are plain CMake and are edited by hand
from then on.

The script never touches a CMakeLists.txt without its "Generated by" first
line (src/CMakeLists.txt and src/xspice/cmpp/CMakeLists.txt are written by
hand), and it deletes generated files whose directory no longer exists.
"""

import os
import re
import sys

TOP = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(TOP, "src")
MARK = "# Generated by cmake/am2cmake.py"

# automake conditional -> CMake condition.  An unknown conditional stops the
# run, so a new one cannot silently drop sources.
AM_COND_MAP = {
    "XSPICE_WANTED":   "NGSPICE_ENABLE_XSPICE",
    "OSDI_WANTED":     "NGSPICE_ENABLE_OSDI",
    "CIDER_WANTED":    "NGSPICE_ENABLE_CIDER",
    "NUMDEV_WANTED":   "NGSPICE_ENABLE_CIDER",
    "NDEV_WANTED":     "NGSPICE_ENABLE_NDEV",
    "KLU_WANTED":      "NGSPICE_ENABLE_KLU",
    "PSS_WANTED":      "NGSPICE_ENABLE_PSS",
    "SP_WANTED":       "NGSPICE_ENABLE_RFSPICE",
    "SENSE2_WANTED":   "NGSPICE_ENABLE_SENSE2",
    "CMATHTESTS":      "NGSPICE_ENABLE_CMATHTESTS",
    "NO_X":            "NOT NGSPICE_ENABLE_X11",
    "NO_HELP":         "NOT NGSPICE_ENABLE_HELP",
    "WINGUI":          "NGSPICE_WINGUI",
    "WINCONSOLE":      "WIN32 AND NOT NGSPICE_WINGUI",
    "WINRESOURCE":     "WIN32",
    "SHWIN":           "WIN32 AND NGSPICE_BUILD_SHARED",
    "SHCYG":           "FALSE",
    "TCLWIN":          "FALSE",
    "TCLCYG":          "FALSE",
    "TCL_MODULE":      "FALSE",
    "SHARED_MODULE":   "NGSPICE_BUILD_SHARED",
    "OLDAPPS":         "NGSPICE_ENABLE_OLDAPPS",
    "CROSS_COMPILING": "CMAKE_CROSSCOMPILING",
    "MAINTAINER_MODE": "FALSE",
    "DEBUG_WANTED":    "FALSE",
    "RELPATH":         "NGSPICE_ENABLE_RELPATH",
    "DLIBS_FULLY_RESOLVED": "NOT APPLE",
}

# Directories that have a Makefile.am but are not part of the simulator core.
NOT_CORE = (
    "xspice/cmpp",      # code model preprocessor, hand-written CMakeLists.txt
    "xspice/icm",       # code models, cmake/NgspiceCodeModels.cmake
    "xspice/verilog",   # Verilog co-simulation, not built
    "xspice/vhdl",      # VHDL co-simulation, not built
)

# Directories whose condition autotools applies when linking (LDADD in
# src/Makefile.am) rather than in SUBDIRS.  Replaces the SUBDIRS condition.
DIR_COND = {
    "frontend/help":  "NGSPICE_ENABLE_X11 AND NOT NGSPICE_WINGUI",
    "frontend/wdisp": "NGSPICE_WINGUI",
    "maths/KLU":      "NGSPICE_KLU_BUNDLED",
}

# Library -> CMake target; every other library goes into ngspice_core.
LIB_TARGET = {
    "libKLU_complex_la": "ngspice_klu_complex",   # compiled with -DCOMPLEX
}
DEFAULT_TARGET = "ngspice_core"

# bison inputs handled by bison_target() in src/CMakeLists.txt
PARSER_INPUTS = ("parse-bison.y", "inpptree-parser.y")

LIB_SOURCES_RE = re.compile(r"^(lib[A-Za-z0-9_]+_la)_SOURCES\s*\+?=\s*(.*)$")
SUBDIRS_RE = re.compile(r"^SUBDIRS\s*\+?=\s*(.*)$")
COMPILED = (".c", ".cc", ".cpp")


def negate(cond):
    if cond.startswith("NOT ") and " AND " not in cond and " OR " not in cond:
        return cond[4:]
    return "NOT (%s)" % cond


def join_conds(stack):
    if not stack:
        return None
    if len(stack) == 1:
        return stack[0]
    return " AND ".join("(%s)" % c for c in stack)


def in_not_core(rel):
    return any(rel == d or rel.startswith(d + "/") for d in NOT_CORE)


def parse(path):
    """-> sources {target: [(cond, file)]}, subdirs [(cond, [names])], parsers"""
    raw = open(path, "r", errors="replace").read().replace("\\\n", " ")
    sources, subdirs, parsers = {}, [], []
    stack = []
    for line in raw.splitlines():
        t = line.strip()
        if not t or t.startswith("#"):
            continue
        word = t.split()[0]
        if word == "if":
            arg = t.split(None, 1)[1].strip()
            name = arg.lstrip("!").strip()
            if name not in AM_COND_MAP:
                sys.exit("%s: unknown automake conditional '%s' -- add it to "
                         "AM_COND_MAP in cmake/am2cmake.py" % (path, name))
            cond = AM_COND_MAP[name]
            stack.append(negate(cond) if arg.startswith("!") else cond)
            continue
        if word == "else":
            stack[-1] = negate(stack[-1])
            continue
        if word == "endif":
            stack.pop()
            continue

        m = SUBDIRS_RE.match(t)
        if m:
            subdirs.append((join_conds(stack), m.group(1).split()))
            continue

        m = LIB_SOURCES_RE.match(t)
        if m:
            target = LIB_TARGET.get(m.group(1), DEFAULT_TARGET)
            for f in m.group(2).split():
                if f.startswith("$"):
                    continue
                if f.endswith(COMPILED):
                    sources.setdefault(target, []).append((join_conds(stack), f))
                elif f.endswith((".y", ".l")):
                    parsers.append(f)
    return sources, subdirs, parsers


def sources_block(target, files, indent=""):
    lines = ["%starget_sources(%s PRIVATE" % (indent, target)]
    lines += ["%s    %s" % (indent, f) for f in files]
    lines[-1] += ")"
    return lines


def render(rel, sources, subdirs, parsers):
    out = [MARK + " from Makefile.am -- edit that file, then run",
           "# python3 cmake/am2cmake.py. Without autotools: delete these two lines.",
           ""]

    for target in sorted(sources, key=lambda t: (t != DEFAULT_TARGET, t)):
        entries = sources[target]
        plain = [f for c, f in entries if c is None]
        if plain:
            out += sources_block(target, plain) + [""]
        conds = []
        for c, _ in entries:
            if c is not None and c not in conds:
                conds.append(c)
        for c in conds:
            out.append("if(%s)" % c)
            out += sources_block(target, [f for cc, f in entries if cc == c], "    ")
            out += ["endif()", ""]

    for f in parsers:
        if f not in PARSER_INPUTS:
            sys.exit("src/%s/Makefile.am: %s is a bison/flex input that "
                     "src/CMakeLists.txt does not process" % (rel, f))
        out += ["# %s: see bison_target() in src/CMakeLists.txt" % f, ""]

    for cond, names in subdirs:
        groups = []
        for n in names:
            if in_not_core(rel + "/" + n):
                continue
            c = DIR_COND.get(rel + "/" + n, cond)
            if groups and groups[-1][0] == c:
                groups[-1][1].append(n)
            else:
                groups.append((c, [n]))
        for c, ns in groups:
            if c is None:
                out += ["add_subdirectory(%s)" % n for n in ns]
            else:
                out.append("if(%s)" % c)
                out += ["    add_subdirectory(%s)" % n for n in ns]
                out.append("endif()")
    return "\n".join(out).rstrip("\n") + "\n"


def main():
    # top level directories: from src/Makefile.am, but src/CMakeLists.txt
    # (hand-written) must add them itself
    _, top_subdirs, _ = parse(os.path.join(SRC, "Makefile.am"))
    top = [n for _, ns in top_subdirs for n in ns if not n.startswith("include/")]
    cm = open(os.path.join(SRC, "CMakeLists.txt")).read()
    have = set(re.findall(r"add_subdirectory\(\s*([A-Za-z0-9_]+)\s*\)", cm))
    missing = [n for n in top if n not in have]
    if missing:
        sys.exit("src/Makefile.am has SUBDIRS %s; add add_subdirectory(%s) "
                 "to src/CMakeLists.txt" % (" ".join(missing), missing[0]))

    result = {}

    def visit(rel):
        sources, subdirs, parsers = parse(os.path.join(SRC, rel, "Makefile.am"))
        result[rel] = render(rel, sources, subdirs, parsers)
        for _, names in subdirs:
            for n in names:
                child = rel + "/" + n
                if in_not_core(child):
                    continue
                if not os.path.isfile(os.path.join(SRC, child, "Makefile.am")):
                    sys.exit("src/%s/Makefile.am lists SUBDIRS '%s', but "
                             "src/%s/Makefile.am does not exist" % (rel, n, child))
                visit(child)

    for n in top:
        visit(n)

    check = "--check" in sys.argv[1:]
    stale = []
    for rel, text in sorted(result.items()):
        path = os.path.join(SRC, rel, "CMakeLists.txt")
        if not os.path.exists(path) or open(path).read() != text:
            stale.append(rel)
    for dp, _, fn in os.walk(SRC):
        rel = os.path.relpath(dp, SRC).replace(os.sep, "/")
        if "CMakeLists.txt" in fn and rel != "." and rel not in result:
            if open(os.path.join(dp, "CMakeLists.txt")).read(len(MARK)) == MARK:
                stale.append(rel)
    if check:
        for r in stale:
            print("out of date: src/%s/CMakeLists.txt" % r)
        sys.exit(1 if stale else 0)

    changed = 0
    for rel, text in sorted(result.items()):
        path = os.path.join(SRC, rel, "CMakeLists.txt")
        if os.path.exists(path):
            old = open(path).read()
            if not old.startswith(MARK):
                sys.exit("src/%s/CMakeLists.txt was not generated by this "
                         "script; not overwriting it" % rel)
            if old == text:
                continue
        with open(path, "w", newline="\n") as fh:
            fh.write(text)
        changed += 1

    removed = []
    for dp, _, fn in os.walk(SRC):
        rel = os.path.relpath(dp, SRC).replace(os.sep, "/")
        if "CMakeLists.txt" in fn and rel != "." and rel not in result:
            path = os.path.join(dp, "CMakeLists.txt")
            if open(path).read(len(MARK)) == MARK:
                os.remove(path)
                removed.append(rel)

    print("%d directories, %d CMakeLists.txt written" % (len(result), changed))
    for r in removed:
        print("removed src/%s/CMakeLists.txt (directory left the build)" % r)


if __name__ == "__main__":
    main()
